from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path
from typing import Protocol, Sequence

from app.services.inference import (
    InferenceResult,
    InferenceService,
    ValidatedModalities,
)
from app.services.integrity_report import (
    IntegrityReportError,
    build_integrity_report,
    generate_case_id,
    write_integrity_report,
)
from app.services.measurements import measure_segmentation
from app.services.nifti_export import NiftiExportError, NiftiExportResult, export_segmentation
from app.services.segmentation_validation import (
    SegmentationValidationError,
    validate_segmentation,
)
from app.services.validation import (
    DEFAULT_MAX_VOXELS,
    MRIValidationError,
    load_and_validate_modalities,
)


LOGGER = logging.getLogger("neuroscope.predict")


class InferenceRunner(Protocol):
    def infer(self, validated: ValidatedModalities) -> InferenceResult: ...


def run_prediction(
    *,
    t1ce: Path,
    t1: Path,
    t2: Path,
    flair: Path,
    output_directory: Path,
    case_id: str | None = None,
    model_path: Path | None = None,
    inference_service: InferenceRunner | None = None,
) -> tuple[NiftiExportResult, Path]:
    """Run the verified local pipeline and write a mask plus Integrity Passport."""
    identifier = case_id or generate_case_id()
    input_paths = {
        "T1ce": t1ce,
        "T1": t1,
        "T2": t2,
        "FLAIR": flair,
    }
    validated_modalities = load_and_validate_modalities(
        input_paths,
        max_voxels=DEFAULT_MAX_VOXELS,
    )
    service = inference_service or InferenceService(model_path=model_path)
    inference_result = service.infer(validated_modalities)
    reference_image = validated_modalities["images"]["T1ce"]
    output_validation = validate_segmentation(
        inference_result.segmentation,
        reference_shape=validated_modalities["shape"],
        reference_affine=validated_modalities["affine"],
        output_affine=inference_result.affine,
        reference_spacing_mm=validated_modalities["spacing_mm"],
        output_spacing_mm=inference_result.spacing_mm,
    )
    spatial_units, _ = reference_image.header.get_xyzt_units()
    measurements = measure_segmentation(
        output_validation.segmentation,
        inference_result.affine,
        spatial_units=spatial_units,
    )
    export_result = export_segmentation(
        output_validation.segmentation,
        reference_image=reference_image,
        segmentation_affine=inference_result.affine,
        output_directory=output_directory,
        case_id=identifier,
    )
    try:
        report = build_integrity_report(
            case_id=identifier,
            input_paths=input_paths,
            validated_modalities=validated_modalities,
            inference_result=inference_result,
            output_validation=output_validation,
            measurements=measurements,
            export_result=export_result,
            input_validation_warnings=validated_modalities.get("warnings", ()),
        )
        report_path = write_integrity_report(
            report,
            output_directory=output_directory,
            case_id=identifier,
        )
    except (IntegrityReportError, NiftiExportError, OSError, ValueError, RuntimeError):
        export_result.path.unlink(missing_ok=True)
        raise
    return export_result, report_path


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Predict a BraTS-coded segmentation on the original MRI grid. "
            "Research and teaching use only; not for clinical diagnosis."
        )
    )
    parser.add_argument("--t1ce", required=True, type=Path, help="T1ce NIfTI path")
    parser.add_argument("--t1", required=True, type=Path, help="T1 NIfTI path")
    parser.add_argument("--t2", required=True, type=Path, help="T2 NIfTI path")
    parser.add_argument("--flair", required=True, type=Path, help="FLAIR NIfTI path")
    parser.add_argument(
        "--output-dir",
        required=True,
        type=Path,
        help="Explicit directory for the NIfTI mask and JSON Integrity Passport",
    )
    parser.add_argument(
        "--case-id",
        help="Optional safe output identifier; a random ID is generated by default",
    )
    parser.add_argument(
        "--model-path",
        type=Path,
        help="Optional local TorchScript model.ts path",
    )
    return parser


def main(arguments: Sequence[str] | None = None) -> int:
    parser = _parser()
    options = parser.parse_args(arguments)
    try:
        export_result, report_path = run_prediction(
            t1ce=options.t1ce,
            t1=options.t1,
            t2=options.t2,
            flair=options.flair,
            output_directory=options.output_dir,
            case_id=options.case_id,
            model_path=options.model_path,
        )
    except (
        MRIValidationError,
        SegmentationValidationError,
        NiftiExportError,
        IntegrityReportError,
        OSError,
        ValueError,
        RuntimeError,
    ) as exc:
        LOGGER.error(
            "Prediction failed (%s).",
            type(exc).__name__,
        )
        print(
            f"Prediction failed ({type(exc).__name__}); verify the input files, "
            "model installation, and output directory.",
            file=sys.stderr,
        )
        return 1
    print(f"Mask: {export_result.filename}")
    print(f"Integrity Passport: {report_path.name}")
    print("Warning: this research/teaching prototype is not for clinical diagnosis.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
